let current = 'en';

function detect() {
  try {
    for (const l of navigator.languages || [navigator.language]) {
      const k = String(l || '').slice(0, 2).toLowerCase();
      if (STRINGS[k]) return k;
    }
  } catch { /* no navigator */ }
  return 'en';
}

export function setLang(pref) { current = pref && pref !== 'auto' && STRINGS[pref] ? pref : detect(); }
export const lang = () => current;
// Locale for dates and times: the browser's own when it matches the language, else the language
export function locale() {
  try { const nav = navigator.language || ''; if (nav.slice(0, 2).toLowerCase() === current) return nav; } catch { /* ignore */ }
  return current;
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

